const test = require('node:test')
const assert = require('node:assert/strict')
const { variant } = require('./app/variant.cjs')
test('preview uses exactly the approved origin, not production or redirects to outsiders', () => {
  const cfg = variant('preview')
  assert.equal(cfg.home, 'https://synca-preview.haerth.cn')
  assert.equal(cfg.allows('https://synca-preview.haerth.cn/auth/email/code'), true)
  for (const value of ['http://synca-preview.haerth.cn', 'https://synca-preview.haerth.cn:8443', 'https://synca.haerth.cn', 'https://synca-preview.haerth.cn.evil.invalid','https://appleid.apple.com']) assert.equal(cfg.allows(value), false)
})
test('preview has a non-production profile, app identity and disabled push', () => {
  const live = variant()
  const preview = variant('preview')
  assert.equal(live.home, 'https://synca.haerth.cn')
  assert.equal(live.bundleId, 'cn.haerth.synca.electron')
  assert.notEqual(live.bundleId, preview.bundleId)
  assert.equal(preview.profile, 'Synca Electron Preview')
  assert.equal(preview.push, false)
  assert.throws(() => variant('typo'))
})
test('local walkthrough rejects anything except its unique virtual origin and fixed loopback port', () => {
  const cfg = variant('local-preview')
  assert.equal(cfg.home, 'https://synca-preview.localhost')
  assert.equal(cfg.upstream, 'http://127.0.0.1:30642')
  assert.equal(cfg.allows('https://synca-preview.localhost/auth/email/code'), true)
  assert.equal(cfg.allows('https://synca-preview.haerth.cn/auth/email/code'), false)
  assert.equal(cfg.allows('https://synca.haerth.cn/'), false)
  assert.notEqual(cfg.bundleId, variant('preview').bundleId)
  assert.notEqual(cfg.profile, variant('preview').profile)
})
