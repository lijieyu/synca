import {rolldown} from 'rolldown';
import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {createHash} from 'node:crypto';
const entry=fileURLToPath(new URL('../src/markdown/native.ts',import.meta.url));
const root=new URL('../../',import.meta.url);
const outputPath='ios/Synca/Resources/markdown-parser.js';
const destination=new URL(outputPath,root);
const manifestDestination=new URL('ios/Synca/Resources/markdown-parser.manifest.json',root);
// The node condition selects the pure entity decoder, never the DOM-based browser decoder.
const bundle=await rolldown({input:entry,platform:'node',resolve:{conditionNames:['node','import','default']}});
const {output}=await bundle.generate({format:'iife',name:'SyncaMarkdown',minify:true,banner:'// Generated by web/scripts/build-markdown-parser.mjs. Do not edit.'});
await bundle.close();
const chunk=output.find(item=>item.type==='chunk');
const packages=new Map();
for(const id of chunk.moduleIds){
 const match=id.match(/^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)/);if(!match)continue;
 const directory=match[1];if(packages.has(directory))continue;
 const metadata=JSON.parse(await readFile(join(directory,'package.json'),'utf8'));
 const licenseName=(await readdir(directory)).find(name=>/^licen[sc]e(?:\.(?:md|txt))?$/i.test(name));
 if(!licenseName)throw new Error(`Missing license for bundled dependency ${metadata.name}`);
 packages.set(directory,{name:metadata.name,text:await readFile(join(directory,licenseName),'utf8')});
}
const notices=[...packages.values()].sort((a,b)=>a.name.localeCompare(b.name,'en')).map(({name,text})=>`/*! ${name}\n${text.replaceAll('*/','* /').trim()}\n*/`).join('\n');
const code=chunk.code+'\n'+notices+'\n';
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const inputs={};
for(const path of ['web/src/markdown/parse.ts','web/src/markdown/native.ts','web/package-lock.json','web/scripts/build-markdown-parser.mjs'].sort()){
 inputs[path]=sha256(await readFile(new URL(path,root)));
}
const manifest=JSON.stringify({version:1,algorithm:'sha256',inputs,output:{path:outputPath,sha256:sha256(code)}},null,2)+'\n';
if(process.argv.includes('--check')){
 if(await readFile(manifestDestination,'utf8')!==manifest)throw new Error('Native Markdown parser manifest is stale; run npm run markdown:bundle in web.');
 if(await readFile(destination,'utf8')!==code)throw new Error('Native Markdown parser is stale; run npm run markdown:bundle in web.');
 console.log('Native Markdown parser matches source.');
}else{await mkdir(dirname(fileURLToPath(destination)),{recursive:true});await writeFile(destination,code);await writeFile(manifestDestination,manifest);console.log('Wrote native Markdown parser.');}
