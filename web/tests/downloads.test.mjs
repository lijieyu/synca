import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const code = ts.transpile(readFileSync(new URL('../src/utils/downloads.ts', import.meta.url), 'utf8'), { module: ts.ModuleKind.ESNext });
const downloads = await import(`data:text/javascript,${encodeURIComponent(code)}`);
const received = [];
let picked = false;
globalThis.window = { setTimeout: () => 0, showDirectoryPicker: () => { picked = true; throw Error('Must use browser destination'); } };
globalThis.document = { body: { appendChild() {} }, createElement: () => ({ click() { received.push(this.download); }, remove() {} }) };
await Promise.all([downloads.saveDownload(new Blob(['one']), '../file.txt'), downloads.saveDownload(new Blob(['two']), 'report.txt')]);
await downloads.saveDownload(new Blob(['safe']), 'control' + String.fromCharCode(0, 10, 31) + '.txt');
await downloads.saveDownload(new Blob(['safe']), '');
assert.deepEqual(received, ['.._file.txt', 'report.txt', 'control___.txt', 'attachment']);
assert.equal(picked, false);
assert.equal(downloads.chooseDownloadDirectory, undefined);
